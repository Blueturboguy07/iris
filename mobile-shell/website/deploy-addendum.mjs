// RC-03 (round5/rc03-website). Appends the "deploy the website pages"
// section to round3-deferred/M-store-screens/website-catalog-v2/DEPLOY.md,
// which this unit owns as a path even though the file's first half is
// written by seed-catalog-v2.mjs (excluded from this unit's owned paths;
// see mobile-shell/website/tests/seed-catalog-v2.test.mjs for the prefix
// check that keeps the two halves from fighting). Idempotent: running it
// twice replaces only the marked section, never duplicates it.

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, "../..");
export const DEPLOY_MD = join(
  REPO,
  "docs/plans/20260928-all-routes/round3-deferred/M-store-screens/website-catalog-v2/DEPLOY.md",
);

export const RC03_MARKER = "<!-- RC-03 website deploy addendum: generated by mobile-shell/website/build-site.mjs, do not edit by hand -->";

function sha256Hex(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function publicURLFor(relativePath) {
  if (relativePath === ".well-known/apple-app-site-association") return "https://publikhq.com/.well-known/apple-app-site-association";
  if (relativePath.startsWith("api/")) return `https://publikhq.com/${relativePath}`;
  if (relativePath === "404.html") return null; // served as the host's custom error document, not its own URL
  if (relativePath === "iris/index.html") return "https://publikhq.com/iris/"; // matches the shared nav's own hub link
  const withoutIndex = relativePath.replace(/\/index\.html$/, "");
  return `https://publikhq.com/${withoutIndex}`;
}

function contentType(path) {
  if (path.endsWith(".png")) return "image/png";
  if (path.endsWith(".json") || path.endsWith("apple-app-site-association")) return "application/json";
  if (path.endsWith(".css")) return "text/css; charset=utf-8";
  return "text/html; charset=utf-8";
}

/** `files`: the Map<relativePath, Buffer> buildSite() returns. */
export function deployAddendumText(files) {
  const rows = [];
  for (const [relativePath, bytes] of files) {
    const url = publicURLFor(relativePath);
    if (url === null) continue;
    rows.push(`| \`${url}\` | \`site/${relativePath}\` | ${contentType(relativePath)} | \`"sha256:${sha256Hex(bytes)}"\` |`);
  }
  return `${RC03_MARKER}

## Website pages (RC-03, round5/rc03-website)

Generated by \`node mobile-shell/website/build-site.mjs\` into \`docs/plans/20260928-all-routes/round5/rc03-website/site/\` (a separate folder from the \`api/\` upload above; that folder is untouched by this generator). Also not deployed yet. Try it locally first: see \`round5/rc03-website/HOW_TO_OPEN.txt\`.

This adds the Guideline 4.7 metadata (age rating, privacy policy link, report contact) to each app's catalog entry, so \`site/api/iris/mobile/\` supersedes the \`api/\` folder above once both are ready to upload together (same package hashes, richer metadata; Nut AI's \`ageRating\` is 13 here, per the owner's decision in \`apple-compliance/DECISIONS.md\` section 1.3, still 4 in the \`api/\` folder above until \`seed-catalog-v2.mjs\` is updated to match). It also adds the human pages and the \`.well-known/apple-app-site-association\` file App Review needs for universal links.

| Address | File in \`round5/rc03-website/site/\` | Content-Type | ETag |
|---|---|---|---|
${rows.join("\n")}

The \`.well-known/apple-app-site-association\` file above uses a placeholder Apple Team ID (\`TEAMIDTBD1\`, see \`mobile-shell/website/site-content.mjs\`) because no Apple Developer Program membership is enrolled yet (\`mobile-shell/native/IrisMobileShellApp/Release.xcconfig\` has an empty \`DEVELOPMENT_TEAM\`, OD-11). **Do not deploy this file until the placeholder is replaced with the real enrolled team id.**

## Check after uploading the website pages

Serve \`site/\` at the web root the same way as the \`api/\` folder above, then \`curl -sI https://publikhq.com/iris/privacy\` and \`https://publikhq.com/.well-known/apple-app-site-association\` should both show \`200\`.
`;
}

export function updatedDeployMD(existingText, files) {
  const markerIndex = existingText.indexOf(RC03_MARKER);
  const base = markerIndex === -1 ? existingText : existingText.slice(0, markerIndex);
  // Trim all trailing whitespace first, so re-running this (or running it a
  // second time after a previous run already appended a section) always
  // produces exactly one blank line before the marker, never a growing run
  // of blank lines.
  const trimmedBase = base.replace(/\s+$/, "");
  return `${trimmedBase}\n\n${deployAddendumText(files)}`;
}

export async function writeDeployAddendum(files) {
  const existing = await readFile(DEPLOY_MD, "utf8");
  await writeFile(DEPLOY_MD, updatedDeployMD(existing, files));
}
